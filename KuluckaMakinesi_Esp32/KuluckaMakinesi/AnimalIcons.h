// ----------------------------------------------------------------------------
// Isim -> Ikon eslestirme tablosu
// AnimalProfiles.h'taki `name` alani ile bire bir eslesir.
// Profil sirasi degisse de ikon atamasi bozulmaz; yeni bir profil eklendiginde
// sadece bu tabloya bir satir eklenir. Eslesmeyen isimlerde default fallback
// (Tavuk) dondurulur.
// ----------------------------------------------------------------------------
struct AnimalIconEntry {
    const char*          name;
    const unsigned char* icon;
    uint16_t             color;  // RGB565 — hayvana ozgu renk
};

inline const AnimalIconEntry* getAnimalIconTable(size_t& count) {
    static const AnimalIconEntry table[] = {
        { "Tavuk",       ICON_TAVUK,      ICON_COLOR_TAVUK      },
        { "Bildircin",   ICON_BILDIRCIN,  ICON_COLOR_BILDIRCIN  },
        { "Kaz",         ICON_KAZ,        ICON_COLOR_KAZ        },
        { "Ordek",       ICON_ORDEK,      ICON_COLOR_ORDEK      },
        { "Hindi",       ICON_HINDI,      ICON_COLOR_HINDI      },
        { "Sulun",       ICON_SULUN,      ICON_COLOR_SULUN      },
        { "Guvercin",    ICON_GUVERCIN,   ICON_COLOR_GUVERCIN   },
        { "Papagan",     ICON_PAPAGAN,    ICON_COLOR_PAPAGAN    },
        { "Devekusu",    ICON_DEVEKUSU,   ICON_COLOR_DEVEKUSU   },
        { "Ipek Bocegi", ICON_IPEKBOCEGI, ICON_COLOR_IPEKBOCEGI },
        { "Ari Kovani",  ICON_ARI,        ICON_COLOR_ARI        },
        { "Keklik",      ICON_KEKLIK,     ICON_COLOR_KEKLIK     },
        { "Tavus Kusu",  ICON_TAVUSKUSU,  ICON_COLOR_TAVUSKUSU  },
        { "Kugu",        ICON_KUGU,       ICON_COLOR_KUGU       },
    };
    count = sizeof(table) / sizeof(table[0]);
    return table;
}

// Profil adina gore ikon girisini (bitmap + renk) dondurur.
// Eslesme bulunamazsa Tavuk fallback olarak doner.
inline const AnimalIconEntry* getAnimalIconEntryByName(const char* name) {
    size_t count = 0;
    const AnimalIconEntry* table = getAnimalIconTable(count);
    if (!name) return &table[0];
    for (size_t i = 0; i < count; ++i) {
        if (strcmp(name, table[i].name) == 0) {
            return &table[i];
        }
    }
    return &table[0];
}

// Geriye donuk uyum: sadece bitmap lazimsa kullan (renk bilgisini kaybeder).
inline const unsigned char* getAnimalIconByName(const char* name) {
    return getAnimalIconEntryByName(name)->icon;
}

